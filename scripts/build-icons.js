// Builds src/images/icons.svg, a single SVG sprite of the Lucide icons the portal uses.
// The sprite is committed, so deployments need no build step. To add an icon, add its
// Lucide name below (see https://lucide.dev/icons) and run: node scripts/build-icons.js
//
// Usage in markup:  <svg class="icon" aria-hidden="true"><use href="/images/icons.svg#calendar"></use></svg>
// Usage in JS:      icon('calendar')   (helper in src/js/config.js)
const fs = require('node:fs');
const path = require('node:path');

const ICONS = [
    // navigation & actions
    'arrow-left', 'arrow-right', 'chevron-down', 'chevron-left', 'chevron-right', 'chevron-up', 'external-link',
    'menu', 'x', 'plus', 'check', 'pencil', 'square-pen', 'trash-2', 'save', 'copy', 'search', 'filter',
    'sliders-horizontal', 'ellipsis', 'refresh-cw', 'undo-2', 'download', 'upload', 'send', 'printer', 'eye', 'link',
    'log-in', 'log-out', 'settings', 'list', 'layout-dashboard', 'house',
    // people & roles
    'user', 'user-round', 'user-plus', 'user-check', 'users', 'shield', 'shield-check', 'scale', 'landmark',
    'briefcase', 'building-2', 'handshake', 'hand', 'key-round', 'lock', 'lock-open',
    // event & logistics
    'calendar', 'calendar-days', 'clock', 'alarm-clock', 'hourglass', 'timer', 'map-pin', 'wallet', 'coins',
    'bed-double', 'utensils', 'coffee', 'ticket', 'rocket', 'mountain-snow', 'snowflake', 'moon', 'sun',
    // communication & files
    'mail', 'mail-check', 'inbox', 'megaphone', 'message-square', 'bell', 'phone', 'smartphone', 'file-text',
    'folder', 'folder-open', 'paperclip', 'book-open', 'clipboard-list', 'laptop',
    // status & competition
    'info', 'circle-alert', 'circle-check', 'circle-x', 'circle-dot', 'triangle-alert', 'ban', 'trophy', 'award',
    'medal', 'star', 'gem', 'sparkles', 'party-popper', 'target', 'zap', 'dices', 'shuffle', 'chart-bar', 'chart-pie'
];

const ROOT = path.join(__dirname, '..');
const SOURCE = path.join(ROOT, 'node_modules', 'lucide-static', 'icons');
const OUT = path.join(ROOT, 'src', 'images', 'icons.svg');

const missing = ICONS.filter(name => !fs.existsSync(path.join(SOURCE, `${name}.svg`)));
if (missing.length) {
    console.error(`Unknown Lucide icons: ${missing.join(', ')}`);
    process.exit(1);
}

const symbols = [...new Set(ICONS)].sort().map(name => {
    const svg = fs.readFileSync(path.join(SOURCE, `${name}.svg`), 'utf8');
    const body = svg
        .replace(/<!--[\s\S]*?-->/g, '')
        .replace(/^[\s\S]*?<svg[^>]*>/, '')
        .replace(/<\/svg>\s*$/, '')
        .split('\n').map(l => l.trim()).filter(Boolean).join('');
    return `<symbol id="${name}" viewBox="0 0 24 24"><g fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</g></symbol>`;
});

const version = require(path.join(ROOT, 'node_modules', 'lucide-static', 'package.json')).version;
fs.writeFileSync(OUT,
    `<!-- Lucide icons v${version} (ISC License, see icons.LICENSE.txt). Generated by scripts/build-icons.js - do not edit. -->\n` +
    `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${symbols.join('\n')}\n</svg>\n`);
fs.copyFileSync(path.join(ROOT, 'node_modules', 'lucide-static', 'LICENSE'), path.join(ROOT, 'src', 'images', 'icons.LICENSE.txt'));
console.log(`Wrote ${symbols.length} icons to ${path.relative(ROOT, OUT)} (${Math.round(fs.statSync(OUT).size / 1024)} KB)`);
